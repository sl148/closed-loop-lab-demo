"""Write RESULTS.md from results/*/summary.json, the solver benchmark, the repair shadow
comparison, the M6 recovery evaluation and the sim3d calibration.

    uv run python scripts/make_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from labloop.metrics import summarize

R = Path("results")

SECTIONS = [
    ("M2: experiment selection (Level 2)", "m2/level2", "designer",
     ["regret", "ttt_h", "ttt_plates", "hit", "rmse", "makespan_h"]),
    ("M2: plate layout (Level 2, BO-TS)", "m2_layout/level2", "layout",
     ["regret", "ttt_h", "hit", "rmse", "makespan_h", "util_lh"]),
    ("M3: schedulers, Level 3 sync rounds (random designer)", "m3/level3", "scheduler",
     ["makespan_h", "idle_h", "resolve_ms", "resolve_p95_ms", "moved_ops", "n_resched", "invalid_plates"]),
    ("M3: schedulers, Level 3 async (6 plates in flight)", "m3_async/level3", "scheduler",
     ["makespan_h", "idle_h", "resolve_ms", "resolve_p95_ms", "moved_ops", "n_resched", "invalid_plates"]),
    ("M4: loop timing (Level 2)", "m4/level2", "variant",
     ["regret", "ttt_h", "ttt_plates", "hit", "makespan_h", "resolve_p95_ms"]),
    ("Level 4: two campaigns, breakdowns, expiry", "level4/level4", "variant",
     ["regret", "ttt_h", "hit", "makespan_h", "resolve_ms", "resolve_p95_ms", "invalid_plates", "n_failures"]),
    ("M8: deck design, Level 2 async (BO-TS, repair, 6 in flight)", "m8/level2", "variant",
     ["makespan_h", "util_lh", "regret", "ttt_h", "hit", "plates"]),
    ("M8: deck design, Level 4 (throughput-aware BO, repair)", "m8/level4", "variant",
     ["makespan_h", "util_lh", "regret", "ttt_h", "hit", "n_failures"]),
]


def summaries(d: Path) -> dict:
    """Per-variant summaries recomputed from the run files (summary.json only holds the
    variants of the last run_level call that wrote the directory)."""
    old = json.loads((d / "summary.json").read_text()) if (d / "summary.json").exists() else {}
    files = {f.stem: f for f in d.glob("*.json") if f.name != "summary.json"}
    order = [k for k in old if k in files] + sorted(k for k in files if k not in old)
    return {k: summarize(json.loads(files[k].read_text())) for k in order}


def fmt(v, sd=None):
    if v is None:
        return "–"
    s = f"{v:.3g}" if abs(v) < 100 else f"{v:.0f}"
    return f"{s} ± {sd:.2g}" if sd is not None else s


def table(summary: dict, cols: list[str]) -> str:
    head = "| variant | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    rows = []
    for name, s in summary.items():
        rows.append(f"| {name} | " + " | ".join(fmt(s.get(c), s.get(c + "_sd")) for c in cols) + " |")
    return head + "\n".join(rows) + "\n"


def at_times(d: Path, hours: tuple[int, ...]) -> str:
    """Share of the best synergy still missed by the recommendation at fixed wall-clock
    times (median and IQR over seeds, averaged over campaigns): the fair comparison when
    variants finish their plate budget at different times."""
    head = "Share of best synergy missed at fixed times (median [IQR] over seeds):\n\n| variant | " + \
           " | ".join(f"{h} h" for h in hours) + " |\n|---|" + "---|" * len(hours) + "\n"
    rows = []
    for f in sorted(d.glob("*.json")):
        if f.name == "summary.json":
            continue
        runs = json.loads(f.read_text())
        cells = []
        for h in hours:
            vals = []
            for r in runs:
                per = []
                for c in r["campaigns"].values():
                    opt = c["optimum"]["excess"]
                    pts = [p for p in c["progress"] if p["t"] <= h * 60 and p["regret"] is not None]
                    per.append(pts[-1]["regret"] / opt if pts else 1.0)
                vals.append(float(np.mean(per)))
            q1, med, q3 = np.percentile(vals, [25, 50, 75])
            cells.append(f"{100 * med:.0f}% [{100 * q1:.0f}-{100 * q3:.0f}]")
        rows.append(f"| {f.stem} | " + " | ".join(cells) + " |")
    return head + "\n".join(rows) + "\n"


def main() -> None:
    out = ["# Results\n",
           "Generated by `scripts/make_results.py` from `results/`. Means over seeds (± std for the headline "
           "metrics). `regret` = true Bliss excess of the optimum minus that of the lab's recommended combination; "
           "`ttt_h` / `ttt_plates` = hours / plates read until the recommendation reaches 90% of the optimum "
           "(averaged over the seeds that reach it; `hit` = share that do).\n"]
    bench = R / "bench_solvers.json"
    if bench.exists():
        rows = json.loads(bench.read_text())
        out.append("## M1: solver sanity on standard instances\n")
        out.append("| instance | optimum | FIFO | priority (LWR) | CP-SAT (20 s) |\n|---|---|---|---|---|\n")
        by = {}
        for r in rows:
            by.setdefault(r["instance"], {})[r["solver"]] = r
        for inst, d in by.items():
            opt = next(iter(d.values()))["optimum"]
            cells = [f"{d[s]['makespan']} ({d[s]['gap_pct']:+.0f}%)" for s in ("fifo", "priority-lwr", "cpsat")]
            out.append(f"| {inst} | {opt} | " + " | ".join(cells) + " |\n")
        out.append("\n")
    for title, d, _, cols in SECTIONS:
        if not (R / d).is_dir():
            continue
        out.append(f"## {title}\n\n" + table(summaries(R / d), cols) + "\n")
        if d == "m2/level2" and not (R / d / "designer=bo-qucb.json").exists():
            out.append("qUCB was stopped before finishing. Like qEI, it picks each plate's ~300 points greedily with "
                       "Monte-Carlo acquisition, at about 1.4 h per seed on the server versus minutes for BO-TS, which draws "
                       "the whole batch at once. qEI's row is above; qUCB adds no further information.\n\n")
        if d.startswith(("m4", "level4")):
            out.append(at_times(R / d, (100, 200, 300)) + "\n")
    sh = R / "m3_shadow/level3/scheduler=repair.json"
    if sh.exists():
        rs = [x for r in json.loads(sh.read_text()) for x in r["reschedules"] if "shadow_obj" in x]
        if rs:
            gaps = np.array([100 * (x["obj"] - x["shadow_obj"]) / x["shadow_obj"] for x in rs])
            t_rep = np.array([x["time_s"] for x in rs])
            t_full = np.array([x["shadow_time_s"] for x in rs])
            out.append("## M3: repair vs a 10 s from-scratch CP-SAT solve (same problem, every replan)\n\n")
            out.append(f"- replans compared: {len(rs)} (3 seeds, Level 3 async)\n"
                       f"- objective gap (repair − full, % of full): median {np.median(gaps):.2f}, p95 "
                       f"{np.percentile(gaps, 95):.2f}, max {gaps.max():.2f}; repair better in "
                       f"{(gaps < 0).mean() * 100:.0f}% of cases\n"
                       f"- solve time: repair median {1000 * np.median(t_rep):.0f} ms (p95 "
                       f"{1000 * np.percentile(t_rep, 95):.0f} ms) vs full {1000 * np.median(t_full):.0f} ms; median speedup "
                       f"{np.median(t_full / np.maximum(t_rep, 1e-4)):.0f}x\n"
                       f"- ops moved per replan (repair): median "
                       f"{np.median([x['moved'] for x in rs]):.0f}\n\n")
    sc = R / "repair_scaling.json"
    if sc.exists():
        rows = json.loads(sc.read_text())
        best = {}
        for r in rows:
            k = (r["plates"], r["seed"])
            best[k] = min(best.get(k, r["obj"]), r["obj"])
        out.append("## Repair vs full re-solve as the backlog grows (one disruption)\n\n"
                   "| plates | solver | gap to best % | solve s | ops moved | valid |\n|---|---|---|---|---|---|\n")
        for n in sorted({r["plates"] for r in rows}):
            for sv in sorted({r["solver"] for r in rows if r["plates"] == n}):
                g = [r for r in rows if r["plates"] == n and r["solver"] == sv]
                gap = np.mean([100 * (r["obj"] - best[(n, r["seed"])]) / best[(n, r["seed"])] for r in g])
                out.append(f"| {n} | {sv} | {gap:.1f} | {np.mean([r['time_s'] for r in g]):.2f} | "
                           f"{np.mean([r['moved'] for r in g]):.0f} | {all(r['valid'] for r in g)} |\n")
        out.append("\n")
    for prov in ("replay", "live", "scripted"):  # replay covers every recorded live seed
        m6 = R / f"m6/summary_{prov}.json"
        if m6.exists():
            s = json.loads(m6.read_text())
            cols = list(next(iter(s.values())).keys())
            out.append(f"## M6: recovery policy, rules vs LLM ({prov})\n\n" + table(s, cols) + "\n")
            break
    cal = R / "sim3d/motion_costs.json"
    if cal.exists():
        mc = json.loads(cal.read_text())
        tips = json.loads((R / "sim3d/tips.json").read_text())
        perc = json.loads((R / "sim3d/perception.json").read_text())
        out.append("## M7: MuJoCo calibration\n\n| move | arm motion s | device overhead s | placement error mm | collisions |\n"
                   "|---|---|---|---|---|\n")
        for k, v in mc["checks"].items():
            out.append(f"| {k} | {v['simulated_s']} | {v['overhead_s']} | {v['placement_err_mm']} | {len(v['collisions'])} |\n")
        out.append(f"\n8-channel pipetting pass: {mc['lh_pass_s']} s (was 30 s assumed).\n\n")
        out.append("| positioning σ (mm) | tip pickup failure, contact sim | analytic Rayleigh tail |\n|---|---|---|\n")
        for r in tips["p_fail"]:
            out.append(f"| {r['sigma_mm']} | {r['p_fail_sim']:.3f} | {r['p_fail_analytic']:.3f} |\n")
        out.append("\n| plate offset (mm) | yaw (deg) | camera detection rate | pose error (mm) |\n|---|---|---|---|\n")
        for r in perc:
            out.append(f"| {r['offset_mm']} | {r['yaw_deg']} | {r['detect_rate']:.2f} | {r['est_err_mm']} |\n")
        out.append("\n")
    l4 = R / "level4_sim3d/level4/summary.json"
    if l4.exists():
        out.append("## M7: Level 4 with MuJoCo-calibrated durations, tip failures and camera perception\n\n" +
                   table(json.loads(l4.read_text()), ["regret", "makespan_h", "n_failures", "corrupt_accepted",
                                                      "invalid_plates"]) + "\n")
    Path("RESULTS.md").write_text("".join(out), encoding="utf-8")
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
